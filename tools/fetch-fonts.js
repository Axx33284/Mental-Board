/* Downloads the Arabic UI font and bakes it into assets/fonts/.
   Run with `npm run fonts`.

   Windows can render Arabic with Segoe UI, but its shaping and spacing are
   noticeably weaker than a purpose-built face — and on a machine without the
   Arabic supplemental fonts installed it falls back to something much worse.
   Bundling one face means Arabic looks identical on every machine.

   Noto Sans Arabic is SIL Open Font License 1.1 (see assets/fonts/OFL.txt). */
const fs = require('fs');
const path = require('path');
const https = require('https');
const crypto = require('crypto');

const OUT = path.join(__dirname, '..', 'src', 'assets', 'fonts');
const FAMILY = 'Noto+Sans+Arabic:wght@400;700';
const CSS_URL = `https://fonts.googleapis.com/css2?family=${FAMILY}&display=swap`;
// asking as a modern browser is what gets woff2 back instead of ttf
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';

function get(url, binary) {
  return new Promise((resolve, reject) => {
    https.get(url, { headers: { 'User-Agent': UA } }, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        res.resume(); return get(res.headers.location, binary).then(resolve, reject);
      }
      if (res.statusCode !== 200) { res.resume(); return reject(new Error(url + ' -> ' + res.statusCode)); }
      const chunks = [];
      res.on('data', (d) => chunks.push(d));
      res.on('end', () => resolve(binary ? Buffer.concat(chunks) : Buffer.concat(chunks).toString('utf8')));
    }).on('error', reject);
  });
}

(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const css = await get(CSS_URL, false);

  // Google splits the family into unicode-range subsets. Keep only the ones
  // that actually carry Arabic — the latin subsets are dead weight here.
  const blocks = css.split('@font-face').slice(1);
  let outCss = '/* Generated by tools/fetch-fonts.js — do not hand-edit.\n' +
               '   Noto Sans Arabic, SIL Open Font License 1.1. */\n';
  let kept = 0, bytes = 0;
  // Noto Sans Arabic is a variable font, so Google hands back the *same* file
  // for 400 and 700. Writing it once per weight shipped two identical 162 KB
  // blobs. Key on the content hash and let both @font-face rules point at one.
  const byHash = new Map();

  for (const block of blocks) {
    const url = (block.match(/url\((https:[^)]+\.woff2)\)/) || [])[1];
    const range = (block.match(/unicode-range:\s*([^;]+);/) || [])[1] || '';
    const weight = (block.match(/font-weight:\s*(\d+)/) || [])[1] || '400';
    if (!url) continue;
    // Must actually contain the Arabic block. Matching loosely on "U+FE7" or
    // "U+FEF" also caught the Latin subset, which carries U+FEFF (the BOM).
    if (!/U\+0600-06FF/i.test(range)) continue;
    const buf = await get(url, true);
    const hash = crypto.createHash('sha1').update(buf).digest('hex');
    let name = byHash.get(hash);
    if (!name) {
      name = `noto-arabic-${weight}-${byHash.size}.woff2`;
      fs.writeFileSync(path.join(OUT, name), buf);
      byHash.set(hash, name);
      bytes += buf.length;
    }
    kept++;
    outCss += `@font-face{font-family:"Noto Sans Arabic";font-style:normal;font-weight:${weight};` +
              `font-display:swap;src:url("fonts/${name}") format("woff2");unicode-range:${range.trim()};}\n`;
  }

  // a rerun that dedupes must not leave the old duplicates behind
  for (const f of fs.readdirSync(OUT)) {
    if (/^noto-arabic-.*\.woff2$/.test(f) && ![...byHash.values()].includes(f)) {
      fs.unlinkSync(path.join(OUT, f));
    }
  }

  if (!kept) throw new Error('no Arabic subsets found — the Google CSS format may have changed');
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'assets', 'fonts.css'), outCss);
  fs.writeFileSync(path.join(OUT, 'OFL.txt'),
    'Noto Sans Arabic is licensed under the SIL Open Font License, Version 1.1.\n' +
    'https://openfontlicense.org\n' +
    'Copyright 2022 The Noto Project Authors (https://github.com/notofonts/arabic)\n');
  console.log(`wrote assets/fonts.css: ${kept} @font-face rules over ` +
              `${byHash.size} woff2 file(s), ${Math.round(bytes / 1024)} KB`);
})().catch((e) => { console.error('failed:', e.message); process.exit(1); });
